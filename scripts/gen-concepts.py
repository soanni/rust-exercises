#!/usr/bin/env python3
"""Pull the `///` doc comments out of every example and write CONCEPTS.md.

Scans every `*.rs` file in the repo (skipping `target/` build dirs) for runs of
`///` doc comments, and emits a Markdown reference grouped by book, where each
entry links back to the file the note lives in.

Usage:
    python3 scripts/gen-concepts.py

Re-run it whenever you add or change doc comments.
"""
from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC_RE = re.compile(r"^\s*///(.*)$")

# Human-readable titles for the top-level book folders, in display order.
BOOK_TITLES = {
    "the-book": "The Rust Programming Language (the-book)",
    "rust-in-month-of-luches": "Rust in a Month of Lunches",
    "oreilly-programming-rust": "Programming Rust (O'Reilly)",
    "async-rust": "Async Rust",
    "tokio": "Tokio",
    "csapp_2016": "Computer Systems: A Programmer's Perspective",
    "rust-for-rustaceans": "Rust for Rustaceans",
}


def extract_blocks(path: pathlib.Path) -> list[str]:
    """Return the doc-comment blocks in a file as Markdown-ready paragraphs."""
    blocks: list[str] = []
    paragraphs: list[str] = []
    current: list[str] = []

    def flush_paragraph() -> None:
        if current:
            paragraphs.append(" ".join(current).strip())
            current.clear()

    def flush_block() -> None:
        flush_paragraph()
        if paragraphs:
            blocks.append("\n\n".join(paragraphs))
            paragraphs.clear()

    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = DOC_RE.match(line)
        if m is None:
            flush_block()
            continue
        text = m.group(1).strip()
        if text:
            current.append(text)
        else:  # blank `///` line = paragraph break within the block
            flush_paragraph()
    flush_block()
    return blocks


def main() -> None:
    # book -> list of (example, relative_path, [blocks])
    found: dict[str, list[tuple[str, str, list[str]]]] = {}

    for path in sorted(ROOT.rglob("*.rs")):
        if "target" in path.parts:
            continue
        rel = path.relative_to(ROOT)
        if len(rel.parts) < 2:
            continue
        book = rel.parts[0]
        example = rel.parts[1]
        blocks = extract_blocks(path)
        if blocks:
            found.setdefault(book, []).append((example, rel.as_posix(), blocks))

    out: list[str] = []
    out.append("# Concept notes")
    out.append("")
    out.append(
        "A quick-reference of the `///` doc comments scattered through the examples — "
        "pinned next to the code that demonstrates each idea, so you can freshen up on "
        "a concept and jump straight to a runnable example."
    )
    out.append("")
    out.append(
        "> Auto-generated by [`scripts/gen-concepts.py`](scripts/gen-concepts.py). "
        "Run `python3 scripts/gen-concepts.py` to refresh after editing doc comments."
    )
    out.append("")

    total = sum(len(entries) for entries in found.values())
    # Table of contents over the books that actually have notes.
    ordered_books = [b for b in BOOK_TITLES if b in found]
    ordered_books += sorted(b for b in found if b not in BOOK_TITLES)
    out.append(f"{total} annotated example(s) across {len(ordered_books)} book(s):")
    out.append("")
    for book in ordered_books:
        title = BOOK_TITLES.get(book, book)
        anchor = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
        out.append(f"- [{title}](#{anchor}) — {len(found[book])} example(s)")
    out.append("")

    for book in ordered_books:
        title = BOOK_TITLES.get(book, book)
        out.append(f"## {title}")
        out.append("")
        for example, relpath, blocks in sorted(found[book]):
            out.append(f"### [`{example}`]({relpath})")
            out.append("")
            for block in blocks:
                for paragraph in block.split("\n\n"):
                    out.append(f"> {paragraph}")
                    out.append("")

    (ROOT / "CONCEPTS.md").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"Wrote CONCEPTS.md: {total} annotated examples across {len(ordered_books)} books.")


if __name__ == "__main__":
    main()
