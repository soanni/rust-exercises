fn main() {
    // addition
    let sum = 2 + 4;
    let sum_f = 2.0 + 4.0;

    // sub
    let sub = 2 - 4;
    let sub_f = 2.0 - 4.0;

    // mul
    let product = 2 * 4;
    let product_f = 2.0 * 4.0;

    // div
    let div = 43 / 5;
    let div_f = 5.0 / 3.0;

    let remainder = 43 % 5;

    println!("sum: {sum}");
    println!("sum_f: {sum_f}");
    println!("sub: {sub}");
    println!("sub_f: {sub_f}");
    println!("product: {product}");
    println!("product_f: {product_f}");
    println!("div: {div}");
    println!("div_f: {div_f}");
    println!("remainder: {remainder}")
}
